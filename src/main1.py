def get_user_choice(options: int) -> int:
    """Получает и возвращает выбор пользователя."""
    while True:
        try:
            choice = int(input("\nВведите номер пункта меню: "))
            if 0 <= choice <= options:
                return choice
            print(f"Ошибка: введите число от 0 до {options}")
        except ValueError:
            print("Ошибка: введите целое число")


def handle_submenu(menu_title: str,
                   submenu_items: List[str],
                   actions: Dict[int, Callable[[], None]]) -> None:
    """Обрабатывает подменю."""
    while True:
        print(f"\n{menu_title} >")
        for i, item in enumerate(submenu_items, 1):
            print(f"{i}. {item}")
        print("0. Назад")

        choice = get_user_choice(len(submenu_items))

        if choice == 0:
            break

        action = actions.get(choice)
        if action:
            try:
                action()
            except Exception as e:
                print(f"\nПроизошла ошибка: {e}")
                print("Пожалуйста, попробуйте еще раз или обратитесь к администратору.")


def main() -> None:
    """Основная функция управления программой."""
    # Действия для подменю
    web_actions = {
        1: display_main_page,
        2: display_events_page
    }

    services_actions = {
        1: display_cashback_categories,
        2: display_investment_page,
        3: display_simple_search,
        4: display_phone_search,
        5: display_person_transfers_search
    }

    reports_actions = {
        1: display_spending_by_category,
        2: display_spending_by_weekday,
        3: display_spending_by_day_type
    }

    while True:
        display_menu()
        main_choice = get_user_choice(3)

        if main_choice == 0:
            print("\nЗавершение работы программы...")
            sys.exit(0)
        elif main_choice == 1:
            handle_submenu(
                "Веб-страницы",
                ["Главная", "События"],
                web_actions
            )
        elif main_choice == 2:
            handle_submenu(
                "Сервисы",
                [
                    "Выгодные категории повышенного кешбэка",
                    "Инвесткопилка",
                    "Простой поиск",
                    "Поиск по телефонным номерам",
                    "Поиск переводов физическим лицам"
                ],
                services_actions
            )
        elif main_choice == 3:
            handle_submenu(
                "Отчеты",
                [
                    "Траты по категории",
                    "Траты по дням недели",
                    "Траты в рабочий/выходной день"
                ],
                reports_actions
            )


if __name__ == "__main__":
    main()